# 语言代码到变量名的映射
LANG_VAR = {
    "zh-CN": "zhCN",
    "zh-TW": "zhTW",
    "en": "en",
    "ja": "ja",
    "ko": "ko",
    "fr": "fr",
    "de": "de",
    "es": "es",
    "ru": "ru",
}

text = FILE.read_text(encoding="utf-8")
le = "\r\n" if crlf else "\n"

injected = 0
for key, translations in AI_KEYS.items():
    for lang_code, value in translations.items():
        var_name = LANG_VAR[lang_code]
        # 找到 "const zhCN: Dict = {" 或 "const en: Dict = {" 等
        # 在该 dict 的末尾（'}'之前）插入新 key
        # 策略：找到 "const <var>: Dict = {" 的起始位置，然后找到该 dict 的结尾
        # 更简单：在每个语言 dict 中，找到最后一个已有的 key-value 行，在其后追加
        
        # 查找该语言 dict 的开头
        pattern_start = f"const {var_name}: Dict = {{"
        start_idx = text.find(pattern_start)
        if start_idx == -1:
            print(f"WARN: could not find {pattern_start}")
            continue
        
        # 从 start_idx 开始，找到对应的 '};'
        # 需要匹配大括号
        brace_count = 0
        dict_start = text.index("{", start_idx)
        i = dict_start
        while i < len(text):
            if text[i] == '{':
                brace_count += 1
            elif text[i] == '}':
                brace_count -= 1
                if brace_count == 0:
                    dict_end = i
                    break
            i += 1
        
        # 检查 key 是否已存在
        escaped_key = key.replace("'", "\\'")
        if f"'{key}'" in text[start_idx:dict_end+1] or f'"{key}"' in text[start_idx:dict_end+1]:
            continue
        
        # 在 dict_end 前插入新行
        # 找到 dict_end 前最后一个非空白字符的位置
        insert_pos = dict_end
        # 回退到最后一个有内容的行
        while insert_pos > dict_start and text[insert_pos-1] in ' \t\r\n':
            insert_pos -= 1
        
        new_line = f"{le}  '{key}': '{value.replace(chr(39), chr(92)+chr(39))}',"
        text = text[:insert_pos] + new_line + text[insert_pos:]
        injected += 1

FILE.write_text(text, encoding="utf-8")
print(f"Done. Injected {injected} key-value pairs across 9 languages.")
